#!/usr/bin/env bun
/**
 * Thin wrapper around wrangler that keeps real resource ids out of the committed config.
 *
 * - No D1_DATABASE_ID in the environment -> runs wrangler against wrangler.toml as-is.
 * - D1_DATABASE_ID set (Bun loads it from .env automatically) -> regenerates
 *   wrangler.local.toml (gitignored) from wrangler.toml with the placeholder replaced,
 *   then runs wrangler with `--config wrangler.local.toml`.
 *
 * Usage: bun scripts/wrangler.ts deploy
 *        bun scripts/wrangler.ts d1 migrations apply docflare-db --remote
 */
import { readFileSync, writeFileSync } from "node:fs";

const SOURCE_CONFIG = "wrangler.toml";
const LOCAL_CONFIG = "wrangler.local.toml";
const PLACEHOLDER = "REPLACE_WITH_YOUR_D1_ID";
const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

const args = process.argv.slice(2);
const databaseId = process.env.D1_DATABASE_ID?.trim();

if (databaseId) {
  if (!UUID_RE.test(databaseId)) {
    console.error(`[scripts/wrangler.ts] D1_DATABASE_ID is not a valid D1 id (expected a UUID).`);
    process.exit(1);
  }

  const source = readFileSync(SOURCE_CONFIG, "utf8");
  if (!source.includes(PLACEHOLDER)) {
    console.warn(
      `[scripts/wrangler.ts] ${SOURCE_CONFIG} has no "${PLACEHOLDER}" placeholder; ignoring D1_DATABASE_ID.`,
    );
  } else {
    const header = `# GENERATED by scripts/wrangler.ts from ${SOURCE_CONFIG}. Do not edit, do not commit.\n`;
    writeFileSync(LOCAL_CONFIG, header + source.replaceAll(PLACEHOLDER, databaseId));
    args.push("--config", LOCAL_CONFIG);
  }
}

const result = Bun.spawnSync(["bunx", "wrangler", ...args], {
  stdio: ["inherit", "inherit", "inherit"],
});
process.exit(result.exitCode ?? 1);
